/**
 * AI architecture knowledge pack generator (P2.8-B, §40–45).
 *
 *   node tools/lego/ai-pack.mjs            # regenerate .ai/
 *   node tools/lego/ai-pack.mjs --check    # fail if .ai/ is stale (CI)
 *
 * WHY GENERATED: a hand-written `.ai/` folder is a second registry, and a second
 * registry always drifts from the first. Everything here is derived from the
 * manifest, the contract lock and the foundation vocabulary — the same data the
 * gates enforce. `--check` makes staleness a build failure, so the pack is
 * either correct or the build is red.
 *
 * CONTEXT LEVELS (§45) — an agent reads the smallest level that answers it:
 *   L0 constitution.md   always; ~40 lines
 *   L1 domains/<id>.md   one LEGO card
 *   L2 contracts.md      the contract and its version rules
 *   L3 recipes/<id>.md   a step-by-step SOP
 *   L4 the source        only when L0–L3 are insufficient
 *
 * Owner: manager. Pure Node, no dependencies.
 */
