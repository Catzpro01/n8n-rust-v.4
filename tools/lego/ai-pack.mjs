function contractIndex(registry) {
  const rows = Object.entries(LOCK.contracts ?? {}).map(([id, row]) => {
    const owner = registry.domains.find((domain) => domain.contract?.id === id);
    return `| \`${id}\` | ${row.version} | ${row.previousVersion ?? '—'} | \`${owner?.id ?? '?'}\` | \`${owner?.owner ?? '?'}\` |`;
  });
  return `${BANNER}
# Contract index

Locked public contracts. A version here is a promise; changing it is an architecture decision.

| Contract | Version | Previous | LEGO | Owner |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

## Version rules

${(LOCK.policy?.rules ?? []).map((rule) => `- ${rule}`).join('\n') || '- see contract-lock.json'}

## Compatibility semantics

- \`major\` — breaking. Needs a compatibility decision, a migration declaration, tests and controlled activation.
- \`minor\` — additive. Consumers keep working; a parent does **not** need a version bump.
- \`patch\` — behaviour-preserving fix.

Checked mechanically by \`compat.mjs\` (\`classifyChange\`, \`satisfies\`, \`planUpgrade\`, \`canReplaceImplementation\`) and gate rule R9.
`;
}

function capabilityIndex(registry) {
  const byCapability = new Map();
  for (const domain of registry.domains) {
    for (const capability of domain.capabilities ?? []) {
      const key = typeof capability === 'string' ? capability : capability.id;
      if (!byCapability.has(key)) byCapability.set(key, []);
      byCapability.get(key).push(domain.id);
    }
  }
  const rows = [...byCapability.entries()].sort().map(([capability, owners]) => `| \`${capability}\` | ${owners.map((owner) => `\`${owner}\``).join(', ')} |`);

  const trustRows = Object.entries(FOUNDATION.trust.levels).map(
    ([level, meta]) => `| \`${level}\` | ${meta.rank} | ${(FOUNDATION.trust.defaultGrants[level] ?? []).map((grant) => `\`${grant}\``).join(', ') || '_none_'} | ${meta.summary} |`,
  );

  return `${BANNER}
# Capability index

## Declared feature capabilities

| Capability | Provided by |
| --- | --- |
${rows.join('\n')}

## Security capabilities and trust

Trust and capability are **separate axes**. A trust level does not imply a capability; capabilities are granted deliberately.

| Trust | Rank | Default grants | Meaning |
| --- | --- | --- | --- |
${trustRows.join('\n')}

Security capabilities: ${FOUNDATION.trust.capabilities.map((capability) => `\`${capability}\``).join(', ')}.
`;
}

